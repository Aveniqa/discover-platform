#!/usr/bin/env node
/**
 * Generates docs/Surfaced-HQ.md — the Obsidian control centre.
 *
 * The repo doubles as an Obsidian vault (.obsidian/ lives at the root and is
 * gitignored). Obsidian's value is graph + backlinks + search over markdown,
 * which only works if the markdown carries frontmatter and [[wikilinks]] —
 * so this writes one dashboard note that is always current: live counts,
 * pipeline health, and links into every other doc.
 *
 * Run by the daily edition workflow, so opening the vault always shows the
 * real state of the site rather than a snapshot someone forgot to update.
 *
 * Usage: node scripts/generate-vault-dashboard.mjs
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const DATA = join(ROOT, "data");
const DOCS = join(ROOT, "docs");

const read = (p) => JSON.parse(readFileSync(p, "utf8"));
const today = new Date().toISOString().slice(0, 10);

const gems = read(join(DATA, "hidden-gems.json"));
const tools = read(join(DATA, "daily-tools.json"));
const archive = read(join(DATA, "archive.json"));
const live = [...gems, ...tools];

// ── Freshness ────────────────────────────────────────────────
const dates = live.map((i) => i.dateAdded).filter(Boolean).sort();
const lastEdition = dates[dates.length - 1] || "unknown";
const addedToday = live.filter((i) => i.dateAdded === lastEdition).length;

// ── Coverage ─────────────────────────────────────────────────
const withShot = live.filter((i) => (i.screenshotUrl || "").startsWith("/screenshots/")).length;
const imageCache = existsSync(join(DATA, "image-cache.json"))
  ? Object.keys(read(join(DATA, "image-cache.json"))).length
  : 0;
const missingSource = live.filter((i) => !i.websiteLink).length;
const archiveMissingSource = archive.filter((i) => !(i.websiteLink || i.sourceLink)).length;

// ── Category spread (what the catalogue actually leans on) ────
const byCategory = {};
for (const i of live) {
  const c = i.category || "Uncategorised";
  byCategory[c] = (byCategory[c] || 0) + 1;
}
const topCategories = Object.entries(byCategory)
  .sort((a, b) => b[1] - a[1])
  .slice(0, 8);

// ── Sibling docs become wikilinks so the graph view connects ──
const docLinks = readdirSync(DOCS)
  .filter((f) => f.endsWith(".md") && f !== "Surfaced-HQ.md")
  .sort()
  .map((f) => `- [[${basename(f, ".md")}]]`)
  .join("\n");

const pct = (n, d) => (d ? Math.round((n / d) * 100) : 0);

const body = `---
title: Surfaced HQ
type: dashboard
updated: ${today}
tags: [surfaced, dashboard, generated]
---

# Surfaced HQ

> [!info] Generated by \`scripts/generate-vault-dashboard.mjs\` on every daily
> edition. Don't hand-edit — your changes are overwritten. Write your own
> notes in a separate file and link to this one.

## Pulse

| | |
|---|---|
| **Live items** | **${live.length}** (${gems.length} hidden gems · ${tools.length} daily tools) |
| **Last edition** | ${lastEdition} (${addedToday} items) |
| **Archive** | ${archive.length} items — permanent, keeps \`/item/<slug>\` alive for search |
| **Real screenshots** | ${withShot}/${live.length} (${pct(withShot, live.length)}%) |
| **Cached photos** | ${imageCache} |
| **Live items missing a link** | ${missingSource} ${missingSource === 0 ? "✅" : "⚠️"} |
| **Archived items without a source** | ${archiveMissingSource} (ledgered as unverifiable — do not retry) |

## Catalogue lean

${topCategories.map(([c, n]) => `- **${c}** — ${n}`).join("\n")}

## Where things live

- Canonical agent instructions → [[../AGENTS|AGENTS]] (\`CLAUDE.md\` just imports it)
- Content pipeline → \`.github/workflows/daily-edition.yml\`
- The 3D world → \`src/components/3d/WorldCanvas.tsx\` + \`BranchingGrowth.tsx\`
- Visual conventions, do-not-regress list → [[../AGENTS|AGENTS § Design language]]

## Docs in this vault

${docLinks}

## Standing human-only actions

These cannot be automated — they need an account owner:

- [ ] X/Twitter API credits (posts fail \`402\`; Bluesky + Pinterest unaffected) — https://developer.x.com
- [ ] Resubmit sitemap after big changes — https://search.google.com/search-console/sitemaps
- [ ] Request AdSense review — https://adsense.google.com
- [ ] Optional: \`SLACK_WEBHOOK_URL\` secret for instant failure pings

## Using this vault with Claude Code

- The repo **is** the vault: \`.obsidian/\` sits at the root and is gitignored,
  so your workspace layout stays local while the notes are versioned.
- Every doc carries YAML frontmatter (\`title\`, \`type\`, \`updated\`, \`tags\`) —
  that is what makes Obsidian search and the graph view useful, and it is
  also what lets Claude Code tell docs apart when scanning.
- Prefer descriptive filenames (\`seo-maintenance.md\`, not \`notes2.md\`); both
  Obsidian and Claude Code match on filename first.
- Keep your own thinking in your own notes. This file is generated — treat
  it as a readout, not a place to write.
`;

writeFileSync(join(DOCS, "Surfaced-HQ.md"), body);
console.log(`✅ docs/Surfaced-HQ.md updated — ${live.length} live items, last edition ${lastEdition}`);
